// Run with Playwright installed, or set PLAYWRIGHT_MODULE to its module entry path.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../', import.meta.url);
const source = name => fs.readFileSync(new URL('src/' + name, root), 'utf8');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || undefined });
try {
  for (const failWorker of [false, true]) {
    const page = await browser.newPage();
    await page.route('http://image-test.local/', route => route.fulfill({ contentType: 'text/html', body: '<html></html>' }));
    await page.goto('http://image-test.local/');
    if (failWorker) await page.evaluate(() => {
      window.Worker = class {
        postMessage({ id }) { queueMicrotask(() => this.onmessage({ data: { id, error: 'An error occurred reading the Blob argument to createImageBitmap' } })); }
        terminate() {}
      };
      window.createImageBitmap = async () => { throw new Error('ImageBitmap unavailable'); };
    });
    await page.addScriptTag({ content: 'const DB_NAME="image-compat", STORE="old", MAX_IMAGES=50; function toast() {}' });
    for (const name of ['image-work.js', 'api.js', 'storage.js', 'tasks.js', 'references.js']) await page.addScriptTag({ content: source(name) });
    const result = await page.evaluate(async () => {
      const canvas = document.createElement('canvas'); canvas.width = 96; canvas.height = 128;
      canvas.getContext('2d').fillRect(0, 0, 96, 128);
      const blob = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'));
      const original = await readableImageBlob(new File([blob], 'import.png', { type: 'image/png' }));
      const saved = await GalleryStore.save({ id: 'import', kind: 'import', blob: original });
      GalleryStore.close();
      const restored = await GalleryStore.original(saved.item);
      const size = await blobDimensions(restored);
      const thumb = await ImageWork.run({ type: 'thumbnail', blob: restored });
      const pale = await ImageWork.run({ type: 'pale', blob: restored });
      const db = await GalleryStore.open();
      const row = await new Promise((resolve, reject) => {
        const request = db.transaction('assets').objectStore('assets').get(saved.item.assetId);
        request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error);
      });
      // Existing Blob rows remain readable, then upload the exact recovered bytes.
      await new Promise((resolve, reject) => {
        const tx = db.transaction('assets', 'readwrite');
        tx.objectStore('assets').put({ id: 'legacy', blob });
        tx.oncomplete = resolve; tx.onerror = () => reject(tx.error);
      });
      const legacy = await GalleryStore.original('legacy');
      const form = new FormData(); form.append('image', legacy, 'source.png');
      // Check serialization with a single boundary generated by the browser.
      const serialized = new Response(form), decoded = await serialized.formData();
      const bytes = await decoded.get('image').arrayBuffer();
      let submissions = 0; const requestedFormats = [], requestedRoutes = [];
      submitAsyncImageTask = async (base, path, bodyFactory) => {
        const body = bodyFactory();
        requestedRoutes.push(typeof body === 'string' ? JSON.parse(body).route : body.get('route'));
        requestedFormats.push(typeof body === 'string' ? JSON.parse(body).output_format : body.get('output_format'));
        const uploaded = typeof body === 'string' ? null : body.get('image') || body.get('image[]');
        if (uploaded && uploaded.size !== restored.size) throw new Error('upload bytes changed');
        submissions++; return { id: 'mock-task' };
      };
      pollAsyncImageTask = async () => ({ blob: restored, points: 1 });
      const settings = { taskApiBase: 'http://image-test.local/api', apiKey: 'test-only' };
      await requestTask({ type: 'lineart', source: { blob: restored }, clientRequestId: 'test-id' }, settings);
      try { await requestTask({ type: 'lineart', source: { blob: new Blob(['broken']) } }, settings); } catch {}
      const params = { subject: '测试', size: '1:1.4' };
      for (const type of ['generation', 'reference', 'edit']) {
        await requestTask({ type, params, instruction: '测试修改', source: { blob: restored }, references: [{ blob: restored }] }, { ...settings, outputFormat: 'jpeg', route: 'line2' });
      }
      await requestTask({ type: 'lineart', outputFormat: 'png', route: 'line1', source: { blob: restored } }, { ...settings, outputFormat: 'jpeg', route: 'line2' });
      const pending = await GalleryStore.save({ id: 'format-pending', kind: 'pending' }, { type: 'generation', params, outputFormat: 'jpeg', route: 'line2' });
      GalleryStore.close();
      const restoredRoute = (await GalleryStore.retry(pending.item.id)).route;
      const restoredFormat = (await GalleryStore.retry(pending.item.id)).outputFormat;
      // FileReader is used if the Blob.arrayBuffer path rejects.
      const fallbackBlob = new Blob([blob], { type: blob.type });
      fallbackBlob.arrayBuffer = async () => { throw new Error('simulated read failure'); };
      const fallbackRead = (await readImageBytes(fallbackBlob)).byteLength === blob.size;
      let brokenMessage;
      try { await blobDimensions(new Blob(['broken'], { type: 'image/png' })); } catch (error) { brokenMessage = error.message; }
      let unreadableMessage;
      try { await readImageBytes({ size: 10, arrayBuffer: async () => new ArrayBuffer(1) }); } catch (error) { unreadableMessage = error.message; }
      // Exercise real save() failure handling, distinguishing quota from other failures.
      const activeDB = await GalleryStore.open();
      const transaction = activeDB.transaction.bind(activeDB);
      const failures = [];
      for (const name of ['QuotaExceededError', 'UnknownError']) {
        activeDB.transaction = () => { throw new DOMException('simulated', name); };
        const failed = await GalleryStore.save({ id: name, kind: 'failed', failureType: 'lineart' });
        failures.push({ cached: failed.cached, message: cacheFailureMessage(failed, '失败记录') });
      }
      activeDB.transaction = transaction;
      ImageWork.close(); GalleryStore.close();
      return { cached: saved.cached, size, thumbnail: thumb.blob.size, pale: pale.blob.size,
        byteStored: row.buffer instanceof ArrayBuffer && !row.blob,
        bytesMatch: Array.from(new Uint8Array(bytes)).join() === Array.from(new Uint8Array(await blob.arrayBuffer())).join(),
        brokenMessage, unreadableMessage, failures, submissions, fallbackRead, requestedFormats, restoredFormat, requestedRoutes, restoredRoute };
    });
    assert.equal(result.submissions, 5, "invalid image must fail before submission");
    assert.deepEqual(result.requestedFormats, ["png", "jpeg", "jpeg", "jpeg", "png"]);
    assert.equal(result.restoredFormat, "jpeg");
    assert.deepEqual(result.requestedRoutes, ["line1", "line2", "line2", "line2", "line1"]);
    assert.equal(result.restoredRoute, "line2");
    assert(result.fallbackRead);
    assert.equal(result.cached, true);
    assert.deepEqual(result.size, { width: 96, height: 128 });
    assert(result.thumbnail > 0 && result.pale > 0);
    assert(result.byteStored && result.bytesMatch);
    assert.match(result.brokenMessage, /无法解码.*重新导入/);
    assert.match(result.unreadableMessage, /原图数据不完整/);
    assert.equal(result.failures[0].cached, false);
    assert.match(result.failures[0].message, /存储空间不足/);
    assert.equal(result.failures[1].cached, false);
    assert.match(result.failures[1].message, /本地保存失败/);
    assert(!result.failures[1].message.includes('不足'));
    await page.close();
  }
  console.log('Image compatibility tests passed: worker and DOM fallback, imported/legacy Blob persistence, multipart byte integrity, invalid images, accurate save errors.');
} finally { await browser.close(); }
